"""Book 02 Section 13.1: labeled two-factor span and financial feasibility."""
import json
import math

def finite(v,name):
    if type(v) not in (int,float):
        raise TypeError(f"{name} must be numeric, excluding bool")
    try:
        x=float(v)
    except OverflowError as exc:
        raise ValueError(f"{name} out of range") from exc
    if not math.isfinite(x):
        raise ValueError(f"{name} must be finite")
    return x

def labels(values,name):
    x=tuple(values)
    if len(x)!=2 or any(type(v) is not str or not v.strip() for v in x) or len(set(x))!=2:
        raise ValueError(f"{name}: two unique nonempty labels required")
    return x

def aligned(source,values,target):
    source=labels(source,"source factors")
    target=labels(target,"target factors")
    values=tuple(values)
    if len(values)!=2 or set(source)!=set(target):
        raise ValueError("factor labels mismatch")
    mapping=dict(zip(source,(finite(v,"target") for v in values)))
    return tuple(mapping[k] for k in target)

def classify(factors,instruments,rows,target_labels,target_values,long_only=False,tolerance=1e-10):
    factors=labels(factors,"factors")
    instruments=labels(instruments,"instruments")
    rows=tuple(tuple(row) for row in rows)
    if len(rows)!=2 or any(len(row)!=2 for row in rows):
        raise ValueError("matrix must be 2x2")
    a=tuple(tuple(finite(v,"sensitivity") for v in row) for row in rows)
    b=aligned(target_labels,target_values,factors)
    tol=finite(tolerance,"tolerance")
    if not 0<tol<1:
        raise ValueError("invalid tolerance")
    (u,v),(w,z)=a
    scale=max(abs(q) for row in a for q in row)
    if scale==0:
        attainable=max(abs(q) for q in b)==0
        return {"in_span":attainable,"unique":False,"positions":None,
                "long_only_feasible":attainable if long_only else None,"runtime_certified":False}
    determinant=(u/scale)*(z/scale)-(v/scale)*(w/scale)
    if abs(determinant)>tol:
        det=u*z-v*w
        x=(finite((b[0]*z-v*b[1])/det,"quantity"),
           finite((u*b[1]-w*b[0])/det,"quantity"))
        return {"in_span":True,"unique":True,
                "positions":dict(zip(instruments,x)),
                "long_only_feasible":all(q>=-tol for q in x) if long_only else None,
                "runtime_certified":False}
    # Rank-one case: compare b against a nonzero column using a 2x2 minor.
    col=(u,w) if max(abs(u),abs(w))>=max(abs(v),abs(z)) else (v,z)
    minor=(col[0]/scale)*(b[1]/max(scale,max(abs(q) for q in b),1.0))-(col[1]/scale)*(b[0]/max(scale,max(abs(q) for q in b),1.0))
    attainable=abs(minor)<=tol
    # For long-only feasibility in the rank-one case, test whether b lies
    # in the nonnegative cone generated by the two collinear columns.
    cone=None
    if long_only:
        if not attainable:
            cone=False
        else:
            pivot=0 if abs(col[0])>=abs(col[1]) else 1
            coefficients=(a[pivot][0],a[pivot][1])
            target=b[pivot]
            cone=any(abs(c)>tol*scale and target/c>=-tol for c in coefficients) or abs(target)<=tol*max(scale,1.0)
    return {"in_span":attainable,"unique":False,"positions":None,
            "long_only_feasible":cone,"runtime_certified":False}

def assessment():
    independent=((2,1),(1,-1))
    redundant=((1,2),(2,4))
    return {"independent":classify(("RATE","CREDIT"),("BOND_A","BOND_B"),independent,
                                   ("CREDIT","RATE"),(1,5),True),
            "requires_short":classify(("RATE","CREDIT"),("BOND_A","BOND_B"),independent,
                                      ("RATE","CREDIT"),(0,3),True),
            "redundant_attainable":classify(("RATE","CREDIT"),("HEDGE_A","HEDGE_B"),redundant,
                                            ("RATE","CREDIT"),(3,6),True),
            "redundant_unattainable":classify(("RATE","CREDIT"),("HEDGE_A","HEDGE_B"),redundant,
                                              ("RATE","CREDIT"),(3,7),True),
            "independent_review_completed":False}

if __name__=="__main__":
    print(json.dumps(assessment(),indent=2,allow_nan=False))
